from __future__ import annotations

import hashlib
from collections.abc import Iterator
from dataclasses import dataclass, field
from typing import Literal

from PIL import Image

from exmekh_lib.config.model_text import MODEL_TEXT
from exmekh_lib.interfaces.message import Message

type UserMessagePart = str | TextsUserMessage | ImagesUserMessage | FilesUserMessage
type UserMessageContent = UserMessagePart | list[UserMessagePart]


class UserMessage(Message["UserMessageContent"]):
    def __init__(
        self,
        content: UserMessageContent,
        name: str = "",
    ) -> None:
        self._content = content
        self._role = "user"
        self._name = name
        self._check_inputs()

    def _check_inputs(self) -> None:
        if not isinstance(self._name, str):
            raise TypeError(MODEL_TEXT.user_name_must_be_a_string)
        parts = self._content if isinstance(self._content, list) else [self._content]
        if not all(
            isinstance(
                part, (str, TextsUserMessage, ImagesUserMessage, FilesUserMessage)
            )
            for part in parts
        ):
            raise TypeError(MODEL_TEXT.user_content_must_be_a_string_or_an_instance)

    def get_message(self) -> UserMessageContent:
        return self._content

    def get_role_name(self) -> str:
        return self._role

    def get_name(self) -> str:
        return self._name

    def iter_content_parts(self) -> Iterator[str | Image.Image | DocumentUserMessage]:
        """Yield text, images and documents in order, expanding their containers."""
        parts = self._content if isinstance(self._content, list) else [self._content]
        for part in parts:
            if isinstance(part, str):
                yield part
            elif isinstance(part, TextsUserMessage):
                yield from part.texts
            elif isinstance(part, ImagesUserMessage):
                yield from part.images
            elif isinstance(part, FilesUserMessage):
                yield from part.documents
            else:
                raise TypeError(
                    MODEL_TEXT.unsupported_user_content_type.format(
                        part_type_name=type(part).__name__
                    )
                )

    def has_attachments(self) -> bool:
        return any(not isinstance(part, str) for part in self.iter_content_parts())

    def with_text_prefix(self, text: str) -> UserMessage:
        """Return a new message without exposing its content containers."""
        parts = self._content if isinstance(self._content, list) else [self._content]
        return UserMessage([text, *parts], name=self._name)

    def message_dump(self) -> dict[str, str]:
        parts = self.iter_content_parts() if self._content is not None else ()
        return {
            "role": self._role,
            "content": "\n".join(self._dump_part(part) for part in parts),
        }

    def _dump_part(self, part: str | Image.Image | DocumentUserMessage) -> str:
        if isinstance(part, Image.Image):
            return MODEL_TEXT.image_hash.format(hash=self._get_hash(part))
        if isinstance(part, DocumentUserMessage):
            return MODEL_TEXT.document_extension_mime_type_hash.format(
                part_name=part.name,
                part_extension=part.extension,
                part_mime_type=part.mime_type,
                hash=self._get_hash(part.file),
            )
        return part

    def _get_hash(self, data: bytes | Image.Image) -> str:
        raw_data = data if isinstance(data, bytes) else data.tobytes()
        return hashlib.sha256(raw_data).hexdigest()


class ErrorUserMessage(UserMessage):
    """User-role feedback generated by the application."""


@dataclass
class TextsUserMessage:
    texts: list[str] = field(default_factory=list)


@dataclass
class ImagesUserMessage:
    images: list[Image.Image] = field(default_factory=list)


@dataclass
class FilesUserMessage:
    documents: list[DocumentUserMessage] = field(default_factory=list)


class DocumentUserMessage:
    def __init__(
        self,
        file: bytes,
        name: str,
        extension: Literal["pdf", "txt", "csv", "json", "xml", "docx", "xlsx", "pptx"],
        mime_type: str = "application/pdf",
    ) -> None:
        self.file = file
        self.name = name
        self.extension = extension
        self.mime_type = mime_type
